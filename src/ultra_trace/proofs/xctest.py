"""XCTest Tier 1 scaffolds for Core crash rules.

Generated code is labeled and not auto-executed. Engineers review and enable
the crash harness locally. See SPEC proof policy and Phase 2 hardening.
"""

from __future__ import annotations

from ultra_trace.core.findings import ProofArtifact
from ultra_trace.frontend.models import SourceSpan


def _safe_type_name(symbol_name: str) -> str:
    cleaned = "".join(ch if ch.isalnum() else "_" for ch in symbol_name)
    cleaned = cleaned.strip("_") or "Symbol"
    if cleaned[0].isdigit():
        cleaned = f"S_{cleaned}"
    return cleaned[:48]


def _assumptions_block(assumptions: tuple[str, ...]) -> str:
    if not assumptions:
        return "        // (none recorded)"
    return "\n".join(f"        // - {item}" for item in assumptions)


def _xctest_scaffold(
    *,
    symbol_name: str,
    test_method: str,
    trigger: str,
    expected: str,
    path_summary: str,
    assumptions: tuple[str, ...],
    harness_lines: tuple[str, ...],
) -> str:
    type_name = f"UltraTraceProof_{_safe_type_name(symbol_name)}"
    harness = "\n".join(f"        // {line}" for line in harness_lines)
    return (
        "import XCTest\n"
        "\n"
        "// Generated by ultra-trace. Review before running.\n"
        "// Do not auto-execute generated proof code in CI by default.\n"
        f"final class {type_name}: XCTestCase {{\n"
        f"    func {test_method}() throws {{\n"
        f"        // Trigger: {trigger}\n"
        f"        // Expected: {expected}\n"
        f"        // Path: {path_summary}\n"
        "        // Assumptions:\n"
        f"{_assumptions_block(assumptions)}\n"
        "        //\n"
        "        // Runnable scaffold (uncomment under a crash-expecting harness):\n"
        f"{harness}\n"
        '        XCTFail("Enable the crash harness above after reviewing the finding.")\n'
        "    }\n"
        "}\n"
    )


def xctest_proof(
    *,
    trigger: str,
    expected: str,
    content: str,
    assumptions: tuple[str, ...],
) -> ProofArtifact:
    return ProofArtifact(
        tier=1,
        kind="xctest",
        supported=True,
        trigger_condition=trigger,
        expected_behavior=expected,
        assumptions=assumptions
        + ("Tier 1 XCTest scaffold; labeled generated code, not auto-executed.",),
        content=content,
        language="swift",
    )


def force_unwrap_xctest(
    *,
    location: SourceSpan,
    symbol_name: str,
    operand_name: str | None,
    path_summary: str,
) -> ProofArtifact:
    name = operand_name or "the optional value"
    trigger = (
        f"Call `{symbol_name}` such that `{name}` is nil, reaching "
        f"{location.file_path}:{location.start_line}."
    )
    expected = "Process crashes on force unwrap of a nil optional."
    assumptions = (
        "Local intra-procedural facts only; no callee descent.",
        f"`{name}` is optional and not proven non-nil on this path.",
    )
    content = _xctest_scaffold(
        symbol_name=symbol_name,
        test_method="test_forceUnwrap_crashesWhenOptionalIsNil",
        trigger=trigger,
        expected=expected,
        path_summary=path_summary,
        assumptions=assumptions,
        harness_lines=(
            f"Reach the force unwrap at line {location.start_line} with `{name}` = nil.",
            f"Example: invoke `{symbol_name}` so the optional is nil.",
            "Observe EXC_BAD_INSTRUCTION / unexpectedly found nil.",
        ),
    )
    return xctest_proof(
        trigger=trigger,
        expected=expected,
        content=content,
        assumptions=assumptions,
    )


def try_bang_xctest(
    *,
    location: SourceSpan,
    symbol_name: str,
    callee_text: str | None,
    path_summary: str,
) -> ProofArtifact:
    callee = callee_text or "the call"
    trigger = (
        f"Call `{symbol_name}` so `{callee}` throws at "
        f"{location.file_path}:{location.start_line}."
    )
    expected = "Process crashes on uncaught error from try!."
    assumptions = (
        "Local intra-procedural facts only; no callee descent.",
        "A throwing target is assumed when not proven non-throwing.",
    )
    content = _xctest_scaffold(
        symbol_name=symbol_name,
        test_method="test_tryBang_crashesWhenCallThrows",
        trigger=trigger,
        expected=expected,
        path_summary=path_summary,
        assumptions=assumptions,
        harness_lines=(
            f"Reach `try!` at line {location.start_line} so `{callee}` throws.",
            f"Example: invoke `{symbol_name}` with inputs that make the call throw.",
            "Observe a runtime crash from the uncaught error.",
        ),
    )
    return xctest_proof(
        trigger=trigger,
        expected=expected,
        content=content,
        assumptions=assumptions,
    )


def forced_cast_xctest(
    *,
    location: SourceSpan,
    symbol_name: str,
    type_name: str | None,
    path_summary: str,
) -> ProofArtifact:
    target = type_name or "the target type"
    trigger = (
        f"Call `{symbol_name}` with a value that is not `{target}` "
        f"at {location.file_path}:{location.start_line}."
    )
    expected = "Process crashes on a failed forced cast."
    assumptions = (
        "Local intra-procedural facts only.",
        "No dominating local `is` check proved the target type on this path.",
    )
    content = _xctest_scaffold(
        symbol_name=symbol_name,
        test_method="test_forcedCast_crashesWhenRuntimeTypeDiffers",
        trigger=trigger,
        expected=expected,
        path_summary=path_summary,
        assumptions=assumptions,
        harness_lines=(
            f"Reach `as! {target}` at line {location.start_line} with a mismatched value.",
            f"Example: invoke `{symbol_name}` so the runtime type is not `{target}`.",
            "Observe a runtime crash from the failed cast.",
        ),
    )
    return xctest_proof(
        trigger=trigger,
        expected=expected,
        content=content,
        assumptions=assumptions,
    )
