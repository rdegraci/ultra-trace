"""pytest-oriented proof scaffolds for Python findings.

Generated code is labeled and not auto-executed. Engineers review locally.
"""

from __future__ import annotations

from ultra_trace.core.findings import ProofArtifact
from ultra_trace.frontend.models import SourceSpan


def pytest_proof(
    *,
    trigger: str,
    expected: str,
    content: str,
    assumptions: tuple[str, ...],
) -> ProofArtifact:
    return ProofArtifact(
        tier=1,
        kind="pytest",
        supported=True,
        trigger_condition=trigger,
        expected_behavior=expected,
        assumptions=assumptions
        + ("Tier 1 pytest scaffold; labeled generated code, not auto-executed.",),
        content=content,
        language="python",
    )


def none_attribute_pytest(
    *,
    location: SourceSpan,
    symbol_name: str,
    operand_name: str | None,
    path_summary: str,
) -> ProofArtifact:
    name = operand_name or "value"
    trigger = (
        f"Call `{symbol_name}` such that `{name}` is None, reaching "
        f"{location.file_path}:{location.start_line}."
    )
    expected = "Attribute access on None raises AttributeError."
    content = (
        "import pytest\n"
        "\n"
        "# Generated by ultra-trace. Review before running.\n"
        "# Do not auto-execute generated proof code in CI by default.\n"
        "\n"
        f"def test_{_safe_name(symbol_name)}_none_attribute() -> None:\n"
        f'    """Trigger: {trigger}\n'
        f"    Expected: {expected}\n"
        f"    Path: {path_summary}\n"
        '    """\n'
        f"    # Harness (uncomment after wiring the subject under test):\n"
        f"    # with pytest.raises(AttributeError):\n"
        f"    #     {symbol_name}(None)  # or otherwise make `{name}` None\n"
        '    pytest.fail("Enable the harness above after reviewing the finding.")\n'
    )
    return pytest_proof(
        trigger=trigger,
        expected=expected,
        content=content,
        assumptions=(
            "Local intra-procedural facts only; no callee descent.",
            f"`{name}` is None or unproven non-None on this path.",
        ),
    )


def assert_pytest(
    *,
    location: SourceSpan,
    symbol_name: str,
    path_summary: str,
) -> ProofArtifact:
    trigger = (
        f"Call `{symbol_name}` so the assert at "
        f"{location.file_path}:{location.start_line} fails "
        "(or is stripped under python -O)."
    )
    expected = "AssertionError when the condition is false; asserts may be disabled."
    content = (
        "import pytest\n"
        "\n"
        "# Generated by ultra-trace. Review before running.\n"
        "# Do not auto-execute generated proof code in CI by default.\n"
        "\n"
        f"def test_{_safe_name(symbol_name)}_assert_risk() -> None:\n"
        f'    """Trigger: {trigger}\n'
        f"    Expected: {expected}\n"
        f"    Path: {path_summary}\n"
        '    """\n'
        "    # Harness (uncomment after wiring the subject under test):\n"
        "    # with pytest.raises(AssertionError):\n"
        f"    #     {symbol_name}(...)  # drive the failing assert path\n"
        '    pytest.fail("Enable the harness above after reviewing the finding.")\n'
    )
    return pytest_proof(
        trigger=trigger,
        expected=expected,
        content=content,
        assumptions=(
            "Assert checks can be removed under optimization (-O).",
            "Local path facts only.",
        ),
    )


def _safe_name(symbol_name: str) -> str:
    cleaned = "".join(ch if ch.isalnum() else "_" for ch in symbol_name)
    cleaned = cleaned.strip("_") or "symbol"
    if cleaned[0].isdigit():
        cleaned = f"f_{cleaned}"
    return cleaned[:48]
